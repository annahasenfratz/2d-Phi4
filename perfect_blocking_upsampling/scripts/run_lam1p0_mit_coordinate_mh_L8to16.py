def save_checkpoint(path: Path, state: CoordinateState) -> None:
    tmp = path.with_suffix(".tmp.npz")
    np.savez_compressed(
        tmp, phi=state.phi, psi=state.psi, coarse=state.coarse, detail=state.detail,
        action=state.action, logq=np.full(len(state.action), np.nan),
        source_config_index=state.source_index, source_native_index=state.source_native_index,
    )
    os.replace(tmp, path)


def detail_map_jacobian_check(kernel: np.ndarray, lc: int) -> dict[str, float | bool | int]:
    """Numerically verify the fixed detail-to-fine linear volume element at L8."""
    if lc > 8:
        return {"performed": False, "reason": "restricted_to_Lc_at_most_8"}
    n_detail = 3 * lc * lc
    n_fine = 4 * lc * lc
    matrix = np.empty((n_fine, n_detail), dtype=np.float64)
    zero_c = np.zeros((1, lc, lc), dtype=np.float32)
    for index in range(n_detail):
        basis = np.zeros((1, 3, lc, lc), dtype=np.float32)
        sector, rem = divmod(index, lc * lc)
        y, x = divmod(rem, lc)
        basis[0, sector, y, x] = 1.0
        phi, _ = inverse_kernel(assemble_psi(zero_c, basis), kernel)
        matrix[:, index] = phi.reshape(-1)
    singular_values = np.linalg.svd(matrix, compute_uv=False)
    rng = np.random.default_rng(7321)
    d0 = rng.standard_normal((1, 3, lc, lc)).astype(np.float32)
    delta = rng.standard_normal((1, 3, lc, lc)).astype(np.float32)
    phi0, _ = inverse_kernel(assemble_psi(zero_c, d0), kernel)
    phi1, _ = inverse_kernel(assemble_psi(zero_c, d0 + delta), kernel)
    phi_delta, _ = inverse_kernel(assemble_psi(zero_c, delta), kernel)
    return {
        "performed": True,
        "detail_dimension": n_detail,
        "fine_dimension": n_fine,
        "min_singular_value": float(singular_values.min()),
        "max_singular_value": float(singular_values.max()),
        "detail_to_fine_log_volume": float(np.log(singular_values).sum()),
        "linearity_max_abs_error": float(np.max(np.abs((phi1 - phi0) - phi_delta))),
        "state_independent": True,
    }


def coarse_kernel_transition(
    coarse: np.ndarray,
    active_sites: np.ndarray,
    *,
    action: ActionSpec,
    sigma: float,
    n_steps: int,
    rng: np.random.Generator,
) -> tuple[np.ndarray, np.ndarray]:
    """Reversible per-site MH kernel whose invariant density is exp(-S_c)."""
    current = np.asarray(coarse, dtype=np.float32).copy()
    accepted = np.zeros(len(current), dtype=np.int64)
    active_flat = np.flatnonzero(active_sites.reshape(-1))
    if len(active_flat) == 0:
        raise RuntimeError("coarse subset contains no active sites")
    lam = float(action.lambda_)
    kappa = float(action.kappa)
    quadratic = 1.0 - 2.0 * lam
    lc = current.shape[1]
    for _ in range(n_steps):
        for flat in rng.permutation(active_flat):
            y, x = divmod(int(flat), lc)
            old = current[:, y, x].astype(np.float64)
            proposal = old + sigma * rng.standard_normal(len(current))
            neighbors = (
                current[:, (y - 1) % lc, x] + current[:, (y + 1) % lc, x]
                + current[:, y, (x - 1) % lc] + current[:, y, (x + 1) % lc]
            ).astype(np.float64)
            delta = quadratic * (proposal * proposal - old * old)
            delta += lam * (proposal**4 - old**4)
            delta -= 2.0 * kappa * (proposal - old) * neighbors
            take = np.log(rng.random(len(current))) < np.minimum(0.0, -delta)
            current[take, y, x] = proposal[take].astype(np.float32)
            accepted += take.astype(np.int64)
    return current, accepted


