@dataclass
class CoordinateState:
    phi: np.ndarray
    psi: np.ndarray
    coarse: np.ndarray
    detail: np.ndarray
    action: np.ndarray
    source_index: np.ndarray
    source_native_index: np.ndarray


def build_state(
    coarse: np.ndarray,
    detail: np.ndarray,
    source_index: np.ndarray,
    source_native_index: np.ndarray,
    *,
    kernel: np.ndarray,
    action: ActionSpec,
) -> CoordinateState:
    psi = assemble_psi(np.asarray(coarse, dtype=np.float32), np.asarray(detail, dtype=np.float32))
    phi, _ = inverse_kernel(psi, kernel)
    fine_action = action_total(phi, action).astype(np.float64)
    return CoordinateState(
        phi=np.asarray(phi, dtype=np.float32),
        psi=np.asarray(psi, dtype=np.float32),
        coarse=np.asarray(coarse, dtype=np.float32),
        detail=np.asarray(detail, dtype=np.float32),
        action=fine_action,
        source_index=np.asarray(source_index, dtype=np.int64).copy(),
        source_native_index=np.asarray(source_native_index, dtype=np.int64).copy(),
    )


def choose_state(old: CoordinateState, new: CoordinateState, accepted: np.ndarray) -> CoordinateState:
    def choose(a: np.ndarray, b: np.ndarray) -> np.ndarray:
        return np.where(accepted.reshape((-1,) + (1,) * (a.ndim - 1)), b, a)

    return CoordinateState(
        phi=choose(old.phi, new.phi),
        psi=choose(old.psi, new.psi),
        coarse=choose(old.coarse, new.coarse),
        detail=choose(old.detail, new.detail),
        action=choose(old.action, new.action),
        source_index=old.source_index.copy(),
        source_native_index=old.source_native_index.copy(),
    )


